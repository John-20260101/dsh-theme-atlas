#!/usr/bin/env node
/**
 * Build step: concatenate the ESM sources into the two plain scripts the
 * harness actually loads.
 *
 * `client.js` is a `window.__ModuleLoader__` module — no bundler, no import
 * graph, because the shell hands plugin bundles straight to the module loader.
 * The sources stay ESM so tests and the preview renderer can import them
 * directly; this script only strips the module syntax and wraps the result.
 *
 * Outputs:
 *   client.js         browser half (theme tokens + rail)
 *   preview/data.js   palettes + copy for the static preview pages
 *   docs/palettes.json  machine-readable palette snapshot quoted by the docs
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const read = (path) => readFile(join(ROOT, path), 'utf8')
const banner = `/* dsh-theme-atlas — generated by scripts/build.mjs. Do not edit by hand. */`

/** Remove `import` statements and `export` prefixes from one ESM source. */
function stripModuleSyntax(source, file) {
  const lines = source.split('\n')
  const kept = []
  let skipping = false
  for (const line of lines) {
    if (!skipping && /^import\s/.test(line)) {
      // Single-line imports only (one statement per line in this repo).
      if (line.trimEnd().endsWith("'") || line.trimEnd().endsWith('"')) continue
      skipping = true
      continue
    }
    if (skipping) {
      if (line.includes("from '") || line.includes('from "')) skipping = false
      continue
    }
    if (/^import\s+['"]/.test(line)) continue
    kept.push(line.replace(/^export\s+(const|let|function|class)\s/, '$1 '))
  }
  const leftover = kept.find((line) => /^\s*(import|export)\s/.test(line))
  if (leftover) throw new Error(`${file}: unhandled module syntax: ${leftover}`)
  return kept.join('\n')
}

const PARTS = ['src/tokens.mjs', 'src/color.mjs', 'src/skins.mjs', 'src/derive.mjs', 'src/runtime.mjs']

const core = []
for (const part of PARTS) {
  core.push(`/* ---- ${part} ---- */`, stripModuleSyntax(await read(part), part))
}

const client = `${banner}
window.__ModuleLoader__.load({
  id: 'dsh-theme-atlas',
  factory(require) {
    'use strict'

${core.join('\n')
  .split('\n')
  .map((line) => (line.length > 0 ? `    ${line}` : line))
  .join('\n')}

    const core = { skins: SKINS, getSkin, deriveSkin, defaultSkin: DEFAULT_SKIN, seriesOf }
    return {
      name: 'themeAtlas',
      inject: [],
      apply(ctx) {
        applyAtlas(ctx, core)
      },
    }
  },
})
`

await writeFile(join(ROOT, 'client.js'), client, 'utf8')

// Preview data: the static pages import this instead of the plugin bundle.
const { SKINS, seriesOf } = await import(join(ROOT, 'src/skins.mjs'))
const { deriveSkin, contrastReport } = await import(join(ROOT, 'src/derive.mjs'))

const palette = {}
for (const skin of SKINS) {
  palette[skin.id] = { ...deriveSkin(skin), contrast: contrastReport(skin) }
}

await mkdir(join(ROOT, 'docs'), { recursive: true })
await writeFile(
  join(ROOT, 'docs/palettes.json'),
  `${JSON.stringify({ version: 1, skins: SKINS, palette }, null, 2)}\n`,
  'utf8',
)

/* Markdown palette reference, regenerated with every build so the numbers in
   the documentation cannot drift from the derivation. */
const md = []
md.push('# Palette reference / 色板参考', '')
md.push('Generated by `npm run build` from `src/skins.mjs` and `src/derive.mjs`. Do not edit by hand.', '')
md.push('| Skin | Material | Accent (light / dark) | Body contrast | Button label |', '| --- | --- | --- | --- | --- |')
for (const skin of SKINS) {
  const rows = contrastReport(skin)
  const light = rows.find((row) => row.mode === 'light')
  const dark = rows.find((row) => row.mode === 'dark')
  md.push(`| ${skin.name.zh} ${skin.name.en} | ${skin.material.zh} | \`${skin.light.accent}\` / \`${skin.dark.accent}\` | ${light.body.toFixed(1)}:1 / ${dark.body.toFixed(1)}:1 | ${light.buttonLabel.toFixed(1)}:1 |`)
}
md.push('')
for (const skin of SKINS) {
  md.push(`## ${skin.name.zh} · ${skin.name.en}`, '')
  md.push(`*${skin.story.zh}*  \n*${skin.story.en}*`, '')
  md.push('| Mode | bg | plate | ink | muted | accent | onAccent | accent2 |', '| --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const mode of ['light', 'dark']) {
    const p = skin[mode]
    md.push(`| ${mode} | \`${p.bg}\` | \`${p.plate}\` | \`${p.ink}\` | \`${p.muted}\` | \`${p.accent}\` | \`${p.onAccent}\` | \`${p.accent2}\` |`)
  }
  const rows = contrastReport(skin)
  md.push('', '| Mode | Body | Secondary | Accent text | Button label | Hairline |', '| --- | --- | --- | --- | --- | --- |')
  for (const row of rows) {
    md.push(`| ${row.mode} | ${row.body.toFixed(2)}:1 | ${row.secondary.toFixed(2)}:1 | ${row.accentText.toFixed(2)}:1 | ${row.buttonLabel.toFixed(2)}:1 | ${row.border.toFixed(2)}:1 |`)
  }
  md.push(`\nKey art: [\`assets/keyart/${skin.id}-1536x1024.png\`](../assets/keyart/${skin.id}-1536x1024.png)\n`)
}
await writeFile(join(ROOT, 'docs/palettes.md'), `${md.join('\n')}\n`, 'utf8')

const preview = `/* generated by scripts/build.mjs — palettes and copy for preview/*.html */
window.__ATLAS_DATA__ = ${JSON.stringify({ skins: SKINS, palette }, null, 2)}
`
await mkdir(join(ROOT, 'preview'), { recursive: true })
await writeFile(join(ROOT, 'preview/data.js'), preview, 'utf8')

console.log(`client.js ${(client.length / 1024).toFixed(1)} kB · ${SKINS.length} skins · preview/data.js written`)
